const LangContext = createContext<{ lang: Lang; t: (zh: string) => string; setLang: (l: Lang) => void }>({
  lang: "zh",
  t: (zh: string) => zh,
  setLang: () => undefined,
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try { const v = localStorage.getItem("fluidpath.lang"); return v === "zh" ? "zh" : "en"; } catch { return "en"; } // 默认英文
  });

  useEffect(() => {
    try { localStorage.setItem("fluidpath.lang", lang); } catch { /* ignore */ }
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (zh: string) => (lang === "zh" ? zh : (EN[zh] ?? zh));

  return <LangContext.Provider value={{ lang, t, setLang }}>{children}</LangContext.Provider>;
}

export function useT() {
  return useContext(LangContext);
}
